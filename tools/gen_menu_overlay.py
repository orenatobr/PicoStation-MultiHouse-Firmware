#!/usr/bin/env python3
"""Generate src/mh/menu_overlay_data.cpp: the 2352 byte menu sectors that the Manager 0.5.5 patches.

usage: gen_menu_overlay.py ORIGINAL_MENU.bin PATCHED_MENU.bin > src/mh/menu_overlay_data.cpp
Both inputs are the 93 raw sector menu blob (picostation_menu.bin) of the Manager, before and after
tools/patch_menu.py. Only the sectors that differ are emitted, each with the FNV-1a hash of its original bytes.
"""
import sys

SEC = 2352


def fnv1a(b: bytes) -> int:
    h = 0x811C9DC5
    for i in range(0, len(b), 4):
        h = ((h ^ int.from_bytes(b[i:i + 4], "little")) * 0x01000193) & 0xFFFFFFFF
    return h


def main() -> None:
    a, b = (open(p, "rb").read() for p in sys.argv[1:3])
    assert len(a) == len(b) and len(a) % SEC == 0
    diff = [i for i in range(len(a) // SEC) if a[i * SEC:(i + 1) * SEC] != b[i * SEC:(i + 1) * SEC]]
    out = ["// Generated by tools/gen_menu_overlay.py, do not edit.", '#include "mh/menu_overlay.h"', "",
           "namespace mh::menu_overlay {", "", f"const uint32_t kCount = {len(diff)};", ""]
    for n, i in enumerate(diff):
        out.append(f"static const uint8_t kSector{n}[{SEC}] = {{")
        s = b[i * SEC:(i + 1) * SEC]
        for j in range(0, SEC, 16):
            out.append("    " + ", ".join(f"0x{x:02x}" for x in s[j:j + 16]) + ",")
        out.append("};")
    out.append("")
    out.append("const Entry kEntries[] = {")
    for n, i in enumerate(diff):
        out.append(f"    {{{i}, 0x{fnv1a(a[i * SEC:(i + 1) * SEC]):08x}u, kSector{n}}},")
    out.append("};")
    out.append("")
    out.append("}  // namespace mh::menu_overlay")
    print("\n".join(out))


main()
