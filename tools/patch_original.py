#!/usr/bin/env python3
"""Add long names (up to 71 characters, docs/LONG_NAMES.md) to YOUR copy of the original PicoStation_MH_V3.uf2.

usage: patch_original.py PicoStation_MH_V3.uf2 patched.uf2 [--cave patch/cave.bin]

The original image is not redistributed: this tool changes four places in it and appends a small block of code
(patch/cave.c) after it. The input must be the unmodified V3 image (its flash contents are checked byte for byte
at every patched site and the whole image is hashed). Nothing else changes, so the boot path stays the original one.
"""
