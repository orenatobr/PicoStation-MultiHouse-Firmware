def bl(src, dst):
    off = dst - (src + 4)
    assert off % 2 == 0 and -(1 << 24) <= off < (1 << 24)
    s = (off >> 24) & 1
    i1, i2 = (off >> 23) & 1, (off >> 22) & 1
    j1, j2 = (~(i1 ^ s)) & 1, (~(i2 ^ s)) & 1
    hw1 = 0xF000 | (s << 10) | ((off >> 12) & 0x3FF)
    hw2 = 0xD000 | (j1 << 13) | (j2 << 11) | ((off >> 1) & 0x7FF)
    return struct.pack("<HH", hw1, hw2)


def uf2_to_flat(data):
    blocks = {}
    for i in range(0, len(data), 512):
        magic0, magic1, flags, addr, n, _, _, fam = struct.unpack_from("<IIIIIIII", data, i)
        if magic0 != 0x0A324655 or magic1 != 0x9E5D5157:
            raise SystemExit("not a UF2 file")
        blocks[addr] = data[i + 32:i + 32 + n]
    lo = min(blocks)
    if lo != BASE:
        raise SystemExit("unexpected UF2 start address %#x" % lo)
    end = max(a + len(b) for a, b in blocks.items())
    flat = bytearray(b"\xff" * (end - BASE))
    for a, b in blocks.items():
        flat[a - BASE:a - BASE + len(b)] = b
    return flat


def flat_to_uf2(flat):
    chunks = [(a, bytes(flat[a:a + 256])) for a in range(0, len(flat), 256)]
    out = bytearray()
    for n, (off, payload) in enumerate(chunks):
        payload = payload.ljust(256, b"\xff")
        hdr = struct.pack("<IIIIIIII", 0x0A324655, 0x9E5D5157, 0x2000, BASE + off, 256, n, len(chunks), FAMILY)
        out += hdr + payload.ljust(476, b"\0") + struct.pack("<I", 0x0AB16F30)
    return bytes(out)


def build_cave():
    """Compile patch/cave.c with arm-none-eabi-gcc; returns (blob, {symbol: address})."""
    elf, binf = ROOT / "build" / "cave.elf", ROOT / "build" / "cave.bin"
    elf.parent.mkdir(exist_ok=True)
    cc = ["arm-none-eabi-gcc", "-mcpu=cortex-m0plus", "-mthumb", "-Os", "-ffreestanding", "-fno-pic", "-fno-exceptions",
          "-fno-asynchronous-unwind-tables", "-nostdlib", "-Wall", "-Wextra", "-Wl,-Ttext=%#x" % CAVE_ADDR,
          "-Wl,-e,case_row_tramp", "-Wl,--build-id=none", "-o", str(elf), str(ROOT / "patch" / "cave.c")]
    subprocess.run(cc, check=True)
    subprocess.run(["arm-none-eabi-objcopy", "-O", "binary", str(elf), str(binf)], check=True)
    syms = {}
    for line in subprocess.run(["arm-none-eabi-nm", str(elf)], check=True, capture_output=True, text=True).stdout.splitlines():
        a, _, name = line.split()
        syms[name] = int(a, 16)
    return binf.read_bytes(), syms


def apply(flat, cave, syms):
    def put(addr, old, new):
        o = addr - BASE
        if bytes(flat[o:o + len(old)]) != old:
            raise SystemExit("unexpected bytes at %#x: %s" % (addr, bytes(flat[o:o + len(old)]).hex()))
        flat[o:o + len(new)] = new
    # 1. Case validator (FUN_10021960): byte +0x3F is the long names flag; only +0x40..+0x4B must stay zero
    put(0x1002199E, bytes.fromhex("0d213f30"), bytes.fromhex("0c214030"))      # movs r1,#13; adds r0,#63 -> #12; #64
    # 2. Disc validator (FUN_10021d84): the extension zone +0x94..+0xFB is no longer required to be zero (CRC still is)
    put(0x10021F0C, bytes.fromhex("fff702fc"), bytes.fromhex("0120c046"))      # bl all_zero -> movs r0,#1; nop
    # 3. Case row of the library listing: FUN_10022284 -> cave (adds case_ext of the Disc record ids[0])
    put(0x1002236E, bytes.fromhex("fff789ff"), bl(0x1002236E, syms["case_row_tramp"]))
    # 4. Disc row title: pointer to the title plus title_ext (cave) instead of the 32 character title
    put(0x10022412, bytes.fromhex("39ab1a78002a"), bl(0x10022412, syms["disc_title_tramp"]) + bytes.fromhex("002a"))
    end = len(flat)
    if BASE + end > CAVE_ADDR:
        raise SystemExit("the image already reaches the cave address")
    flat.extend(b"\xff" * (CAVE_ADDR - BASE - end))
    flat.extend(cave)
    return flat


def embedded_cave():
    import base64
    return base64.b64decode("".join(CAVE_B64)), dict(CAVE_SYMS)


def embed():
    """Rebuild patch/cave.c and rewrite the generated block of this file (needs arm-none-eabi-gcc)."""
    import base64, re
    blob, syms = build_cave()
    b64 = base64.b64encode(blob).decode()
    block = "# --- generated by tools/patch_original.py --embed (patch/cave.c, arm-none-eabi-gcc 14.2.Rel1) ---\n"
    block += "CAVE_B64 = (\n" + "".join('    "%s"\n' % b64[i:i + 100] for i in range(0, len(b64), 100)) + ")\n"
    block += 'CAVE_SYMS = {"case_row_tramp": %#x, "disc_title_tramp": %#x}\n# --- end generated ---\n' % (
        syms["case_row_tramp"], syms["disc_title_tramp"])
    path = Path(__file__).resolve()
    text = re.sub(r"# --- generated by .*?# --- end generated ---\n", lambda _: block, path.read_text(), flags=re.S)
    path.write_text(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?")
    ap.add_argument("dst", nargs="?")
    ap.add_argument("--embed", action="store_true", help="developer: rebuild patch/cave.c into this file")
    ap.add_argument("--rebuild", action="store_true", help="developer: compile patch/cave.c instead of the embedded code")
    args = ap.parse_args()
    if args.embed:
        return embed()
    if not (args.src and args.dst):
        ap.error("source and destination UF2 are required")
    flat = uf2_to_flat(Path(args.src).read_bytes())
    if hashlib.sha256(flat[:265216]).hexdigest() != IMAGE_SHA256 or any(b != 0xFF for b in flat[265216:]):
        raise SystemExit("this is not the unmodified PicoStation_MH_V3 image (sha256 of its flash contents differs)")
    cave, syms = build_cave() if args.rebuild else embedded_cave()
    out = apply(flat, cave, syms)
    Path(args.dst).write_bytes(flat_to_uf2(out))
    print("wrote %s (%d bytes of code at %#x, entry points %#x and %#x)" % (
        args.dst, len(cave), CAVE_ADDR, syms["case_row_tramp"], syms["disc_title_tramp"]))


if __name__ == "__main__":
    main()
